import { CryptoDigestAlgorithm, digestStringAsync } from 'expo-crypto';
import { ApiError } from '@/lib/api';
import { fetchHealth } from '@/lib/health';
import { cachedClip, discardClip, storeClip } from './clipCache';
import { requestSpeech, type SpeechRequest } from './speechApi';

export { discardClip };
export type { SpeechRequest };

export interface NaturalVoiceInfo {
  /** Changes when the server's model or delivery style changes; part of every cache key. */
  version: string;
  voices: string[];
  defaultVoice: string;
}

/** The server's natural-voice settings, or null when it has none (offline, switched off, older server). */
export async function naturalVoiceInfo(): Promise<NaturalVoiceInfo | null> {
  return (await fetchHealth())?.naturalVoice ?? null;
}

let blockedUntil = 0;

/** True while the server recently said no (daily allowance used, switched off): use the phone's voice meanwhile. */
export function naturalVoiceBlocked(): boolean {
  return Date.now() < blockedUntil;
}

function nextUtcMidnight(): number {
  const now = new Date();
  return Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate() + 1);
}

/** Remembers a refusal so the next steps don't wait on requests that will fail too. */
export function noteSpeechFailure(error: unknown): void {
  if (!(error instanceof ApiError)) return;
  if (error.code === 'speech_limit') blockedUntil = nextUtcMidnight();
  else if (error.status === 503 || error.code === 'ai_unavailable' || error.code === 'not_configured') blockedUntil = Date.now() + 10 * 60_000;
  else if (error.code === 'rate_limited' || error.code === 'unauthorized') blockedUntil = Date.now() + 60_000;
}

async function clipKey(request: SpeechRequest, version: string): Promise<string> {
  const digest = await digestStringAsync(
    CryptoDigestAlgorithm.SHA256,
    JSON.stringify([version, request.voice, request.language, request.pace, request.text]),
  );
  return digest.slice(0, 40);
}

const inflight = new Map<string, Promise<string>>();

/**
 * A playable URI for a clip: from this device's cache, or generated by the server. Concurrent
 * callers share one request, and a request keeps going if a caller stops waiting for it, so the
 * clip is ready next time.
 */
export async function loadClip(request: SpeechRequest): Promise<string> {
  const info = await naturalVoiceInfo();
  if (!info) throw new ApiError(503, 'ai_unavailable', 'Natural voice is unavailable', { reason: 'speech_disabled' });
  const key = await clipKey(request, info.version);
  const hit = cachedClip(key);
  if (hit) return hit;
  let job = inflight.get(key);
  if (!job) {
    job = requestSpeech(request)
      .then((bytes) => storeClip(key, bytes))
      .finally(() => inflight.delete(key));
    inflight.set(key, job);
  }
  return job;
}

// Prefetching: at most two clips generate at once, so the one the cook is waiting for isn't starved.
const queue: SpeechRequest[] = [];
let running = 0;

const same = (a: SpeechRequest, b: SpeechRequest) =>
  a.text === b.text && a.language === b.language && a.voice === b.voice && a.pace === b.pace;

function pump() {
  while (running < 2 && queue.length && !naturalVoiceBlocked()) {
    const request = queue.shift()!;
    running++;
    loadClip(request)
      .catch(noteSpeechFailure)
      .finally(() => {
        running--;
        pump();
      });
  }
}

export function prefetchClips(requests: SpeechRequest[]): void {
  for (const request of requests) if (!queue.some((queued) => same(queued, request))) queue.push(request);
  pump();
}

export function cancelPrefetch(): void {
  queue.length = 0;
}
